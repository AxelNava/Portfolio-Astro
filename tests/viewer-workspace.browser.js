async page => {
  page.setDefaultTimeout(4000);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:4323/');
  await page.goto('http://127.0.0.1:4323/#project-web');
  const trigger = page.locator('#project-web .project-preview a');
  await trigger.click();
  const viewer = page.locator('#image-viewer');
  const tab = page.locator('[data-viewer-tab]');
  check(await tab.isVisible(), 'viewer tab must appear in the workspace header');
  check(await viewer.isVisible(), 'viewer panel must be visible');
  check(await page.locator('[data-viewer-square]').count() === 6, 'each image needs a square indicator');
  check(await page.locator('[data-viewer-square][aria-current="true"]').count() === 1, 'one square must indicate current image');
  await page.waitForFunction(() => document.querySelector('[data-viewer-image]').naturalWidth > 0);
  await page.evaluate(() => { window.visitedViewerImage = document.querySelector('[data-viewer-image]'); });
  await page.locator('[data-viewer-next]').click();
  check(await page.locator('[data-viewer-counter]').textContent() === '2 / 6', 'gallery navigation must still work');
  check(await page.locator('[data-viewer-square]').nth(1).getAttribute('aria-current') === 'true', 'square indicator must follow the image');
  await page.locator('[data-viewer-prev]').click();
  check(await page.evaluate(() => window.visitedViewerImage === document.querySelector('[data-viewer-image]')), 'visited image element must be reused in this page');
  await page.locator('[data-viewer-next]').click();
  await page.locator('[data-portfolio-tab]').click();
  check(await trigger.isVisible(), 'portfolio selection must remain available');
  check(!(await viewer.isVisible()), 'portfolio tab hides viewer');
  await tab.click();
  check(await viewer.isVisible(), 'viewer tab restores the panel');
  check(await page.locator('[data-viewer-counter]').textContent() === '2 / 6', 'viewer tab preserves selected image');
  await page.locator('.skip-link').focus();
  await page.keyboard.press('Enter');
  check(await page.locator('#experience').isVisible(), 'skip link must return to visible experience');
  check(!(await viewer.isVisible()), 'skip link must hide viewer');
  await page.locator('#tab-projects').click();
  await page.locator('#tab-project-piano').click();
  await tab.click();
  await page.locator('[data-viewer-close]').click();
  check(await page.locator('[data-portfolio-tab]').evaluate(element => element === document.activeElement), 'hidden opener must fall back to portfolio tab');
  return 'passed';
}
